"""Phase 7 checks on the generated memo and README block. Skipped until `make report` has run."""

import pytest

from coorsfit.config import ROOT
from coorsfit.report import README_END, README_START

MEMO = ROOT / "reports" / "memo.md"
pytestmark = pytest.mark.skipif(not MEMO.exists(), reason="run `make report` first")


def test_memo_is_fully_rendered_and_labels_the_appendix_illustrative():
    text = MEMO.read_text()
    assert "{" not in text and "}" not in text  # no unfilled template fields
    assert "illustrative only" in text.lower()
    body = text.split("## Appendix")[0]
    assert len(body.split()) < 650  # about one page before the appendix


def test_readme_results_block_is_generated():
    text = (ROOT / "README.md").read_text()
    block = text[text.index(README_START) : text.index(README_END)]
    assert "generated by `make report`" in block
    assert "wOBA points" in block
